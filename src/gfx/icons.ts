export function buildIcons(): Record<string, PixelCanvas> {
  const out: Record<string, PixelCanvas> = {};
  for (const [k, rows] of Object.entries(I)) {
    const p = new PixelCanvas(14, 14);
    p.template(rows, 1, 1);
    p.outline('ink');
    out[k] = p;
  }
  return out;
}
