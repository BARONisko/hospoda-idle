export function buildActDecorArt(): Record<string, PixelCanvas> {
  const out: Record<string, PixelCanvas> = {};
  for (const [k, rows] of Object.entries(A)) {
    const w = Math.max(...rows.map((r) => r.length));
    out[k] = new PixelCanvas(w + 2, rows.length + 2).template(rows, 1, 1).outline('ink');
  }
  return out;
}
